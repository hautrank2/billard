"""Score detector-free visual references, coarse shot-clock timing and cached-clip overlap."""

import argparse
import csv
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / ".training-tools"))
import cv2
import numpy as np


def descriptors(path, start, stop):
    cap = cv2.VideoCapture(str(path))
    cap.set(cv2.CAP_PROP_POS_FRAMES, start)
    result = []
    for _ in range(start, stop):
        ok, frame = cap.read()
        if not ok:
            break
        frame = cv2.resize(frame, (160, 90))
        # Moving player/cloth area rather than a nearly static sponsor logo.
        result.append(cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)[30:85, 60:160].astype(np.float32))
    cap.release()
    return np.array(result)


def feasible_clock_rates(times, counts, tolerance=1.0):
    rates = np.linspace(.5, 1.5, 10001)
    possible = []
    times, counts = np.array(times), np.array(counts)
    for rate in rates:
        lower = float(np.max(counts - tolerance + rate * times))
        upper = float(np.min(counts + tolerance + rate * times))
        if lower <= upper + 1e-9:
            possible.append(float(rate))
    return [min(possible), max(possible)] if possible else None


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pilot-root", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    if (args.out / "reference-audit.json").exists():
        parser.error("Use a new version directory")
    args.out.mkdir(parents=True, exist_ok=True)
    root = args.pilot_root
    labels_path = root / "pilot-002/crossview-001/visual-labels.json"
    labels = json.loads(labels_path.read_text(encoding="utf-8"))
    observation_path = root / "pilot-002/validation-002/observations.csv"
    with observation_path.open(encoding="utf-8", newline="") as handle:
        observations = {int(row["frame"]): row for row in csv.DictReader(handle)}
    scores = []
    for label in labels["cue_ball_centers"]:
        observation = observations[label["frame"]]
        manual = np.array(label["center_px"])
        baseline = np.array([float(observation["x_px"]), float(observation["y_px"])])
        edge = np.array([float(observation["edge_x_px"]), float(observation["edge_y_px"])]) if observation["edge_x_px"] else None
        scores.append({"frame": label["frame"], "visual_label_px": manual.tolist(), "color_center_px": baseline.tolist(),
                       "edge_center_px": edge.tolist() if edge is not None else None,
                       "color_label_difference_px": float(np.linalg.norm(baseline - manual)),
                       "edge_label_difference_px": float(np.linalg.norm(edge - manual)) if edge is not None else None})
    color_errors = [row["color_label_difference_px"] for row in scores]
    edge_errors = [row["edge_label_difference_px"] for row in scores if row["edge_label_difference_px"] is not None]
    # Manually read from shot-clock-reference.jpg, not generated by OCR or a detector.
    clock_times = [0, 2, 4, 6, 8, 10, 12, 14]
    clock_counts = [19, 18, 16, 14, 12, 9, 8, 6]
    clock_slope = float(np.polyfit(clock_times, clock_counts, 1)[0])
    clock_rates = feasible_clock_rates(clock_times, clock_counts)
    first = root / "pilot-001/media/source.mp4"
    second = root / "pilot-002/media/source.mp4"
    a = descriptors(first, 1440, 1800)
    b = descriptors(second, 0, 180)
    alignment = []
    # Request offsets differ by 26 seconds = 1560 frames at 60fps.
    # Compare up to 3 seconds, requiring at least one second of actual overlap.
    for start in range(1440, 1741):
        count = min(len(b), 1800 - start)
        if count < 60:
            continue
        error = float(np.mean(np.abs(a[start - 1440:start - 1440 + count] - b[:count])))
        alignment.append({"first_clip_start_frame": start, "compared_frames": count, "mean_absolute_gray_difference": error})
    alignment.sort(key=lambda row: row["mean_absolute_gray_difference"])
    best = alignment[0]
    best["difference_from_requested_offset_frames"] = best["first_clip_start_frame"] - 1560
    best["difference_from_requested_offset_seconds"] = best["difference_from_requested_offset_frames"] / 60
    close = [row["first_clip_start_frame"] for row in alignment if row["mean_absolute_gray_difference"] <= best["mean_absolute_gray_difference"] + .2]
    result = {
        "status": "visual_reference_and_timing_audit_complete",
        "script_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        "labels_sha256": hashlib.sha256(labels_path.read_bytes()).hexdigest(),
        "source_sha256": {"pilot-001": hashlib.sha256(first.read_bytes()).hexdigest(), "pilot-002": hashlib.sha256(second.read_bytes()).hexdigest()},
        "center_reference": {
            "method": labels["method"], "expert_ground_truth": False,
            "visual_label_uncertainty_px": labels["label_uncertainty_px"], "samples": scores,
            "color_median_difference_px": float(np.median(color_errors)), "color_max_difference_px": max(color_errors),
            "edge_found_samples": len(edge_errors),
            "edge_median_difference_px": float(np.median(edge_errors)) if edge_errors else None,
            "edge_max_difference_px": max(edge_errors) if edge_errors else None,
            "decision": "Do not change production detector from nine approximate same-agent labels. Retain both observations and uncertainty."
        },
        "shot_clock": {
            "pilot": "pilot-001", "sample_frames": [int(t * 60) for t in clock_times],
            "clip_times_s": clock_times, "visually_read_remaining_seconds": clock_counts,
            "linear_remaining_clock_seconds_per_video_second": clock_slope,
            "display_uncertainty_seconds": 1.0, "feasible_clock_seconds_per_video_second": clock_rates,
            "interpretation": "These pre-shot samples support approximately real-time playback at the coarse one-second display scale; they do not prove 60 independent motion samples per second or the speed of every later replay."
        },
        "overlap_alignment": {"expected_first_clip_start_frame": 1560, "best": best,
                              "near_best_frame_range": [min(close), max(close)], "best_candidates": alignment[:5],
                              "limitation": "Relative alignment of cached re-encoded clips, not an independent absolute YouTube timestamp measurement."},
        "motion_time_axis": "Original decoded presentation timestamps, with near-hold groups from validation-002. Never evenly resample after removing holds.",
        "real_time_phase_approved": False, "physics_fit_approved": False
    }
    (args.out / "reference-audit.json").write_text(json.dumps(result, indent=2), encoding="utf-8")
    print(json.dumps({"center_reference": {key: value for key, value in result["center_reference"].items() if key != "samples"},
                      "shot_clock": result["shot_clock"], "overlap_alignment": result["overlap_alignment"]}, indent=2))


if __name__ == "__main__":
    main()
